// Generic CSV parsing helpers shared by every admin CSV import wizard (products, customers, ...).
// Extracted out of products-import.ts once a second real entity (customers) needed the exact same
// parser rather than a duplicated copy.

/** Minimal RFC4180 CSV parser -- handles quoted fields with embedded commas/newlines/escaped
 * quotes. No external dependency needed at this scale (admin-uploaded catalogs, not arbitrary
 * user-generated CSV). */
export function parseCsv(text: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = "";
  let inQuotes = false;
  let i = 0;
  const n = text.length;
  while (i < n) {
    const ch = text[i];
    if (inQuotes) {
      if (ch === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i += 2;
          continue;
        }
        inQuotes = false;
        i += 1;
        continue;
      }
      field += ch;
      i += 1;
      continue;
    }
    if (ch === '"') {
      inQuotes = true;
      i += 1;
      continue;
    }
    if (ch === ",") {
      row.push(field);
      field = "";
      i += 1;
      continue;
    }
    if (ch === "\r") {
      i += 1;
      continue;
    }
    if (ch === "\n") {
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
      i += 1;
      continue;
    }
    field += ch;
    i += 1;
  }
  if (field.length > 0 || row.length > 0) {
    row.push(field);
    rows.push(row);
  }
  return rows.filter((r) => r.some((cell) => cell.trim() !== ""));
}

export function toNumberOrNull(v: string | undefined): number | null {
  if (v == null || v.trim() === "") return null;
  const n = Number(v);
  return Number.isFinite(n) ? n : null;
}

export function toBoolOrNull(v: string | undefined): boolean | null {
  if (v == null || v.trim() === "") return null;
  return ["true", "1", "yes", "ja"].includes(v.trim().toLowerCase());
}

export function str(v: string | undefined): string | null {
  return v == null || v.trim() === "" ? null : v.trim();
}

export function csvEscape(value: unknown): string {
  const s = value == null ? "" : String(value);
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}
